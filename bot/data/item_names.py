def item_display_name(item_id: str, fallback: str, lang: str | None = None) -> str:
    """Возвращает название предмета на выбранном языке."""
    if normalize_lang(lang or get_language()) == "en":
        return ITEM_NAMES_EN.get(item_id, fallback)
    return fallback
